import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { resolveReference } from "../frontend/src/engine/paths.js";
import { DRY_HOP_VALUE_LABELS } from "../frontend/src/views/registry/dry-hops.js";
import { HOP_FORM_LABELS } from "../frontend/src/views/registry/hops.js";
import { WATER_IONS } from "../frontend/src/views/registry/water.js";
import { readArtifact } from "./artifact-inventory.mjs";

const readJson = (rel) =>
  JSON.parse(readFileSync(fileURLToPath(new URL(`../${rel}`, import.meta.url)), "utf8"));

const checklist = readJson("data/seeds/brew-checklist.json");
const rests = readJson("data/seeds/mash-rests.json");
const labels = readJson("data/labels.json");

const CHECKLIST_LEVEL_LABELS = Object.fromEntries(
  checklist.levels.map((level) => [level.id, level.name])
);
const MASH_REST_LABELS = Object.fromEntries(
  Object.values(rests).map((rest) => [rest.rest_id, rest.name])
);
const ION_LABELS = Object.fromEntries(WATER_IONS.map(({ ion, label }) => [ion, label]));

const INJECTED_OPTION_LABELS = {
  "batch.boil_hops.product_form": HOP_FORM_LABELS,
  "batch.whirlpool_hops.product_form": HOP_FORM_LABELS,
  "batch.checklist_level": CHECKLIST_LEVEL_LABELS,
  "mash.rests.rest_id": MASH_REST_LABELS,
  "batch.dry_hops.product_type": DRY_HOP_VALUE_LABELS.hop_product_form,
  "batch.dry_hops.application_event": DRY_HOP_VALUE_LABELS.hop_application_event,
  "batch.dry_hops.contact_until": DRY_HOP_VALUE_LABELS.hop_contact_until,
};

const KEY_ORDER = [
  "label",
  "unit",
  "displayUnit",
  "decimals",
  "symbol",
  "control",
  "hint",
  "optionLabels",
];

export function buildGeneratedRegistry() {
  const artifact = readArtifact();
  const registry = {};
  for (const path of Object.keys(labels).sort()) {
    if (!resolveReference(artifact, path)) {
      throw new Error(`data/labels.json path does not resolve: ${path}`);
    }
    const source = { ...labels[path] };
    if (!source.label && path.startsWith("water.target_profile.")) {
      const ion = path.split(".").at(-1);
      if (ION_LABELS[ion]) source.label = ION_LABELS[ion];
    }
    if (INJECTED_OPTION_LABELS[path]) {
      source.optionLabels = INJECTED_OPTION_LABELS[path];
    }
    const entry = {};
    for (const key of KEY_ORDER) if (key in source) entry[key] = source[key];
    if (!entry.label) {
      throw new Error(`data/labels.json entry has no label: ${path}`);
    }
    registry[path] = entry;
  }
  return registry;
}

export function renderRegistry(registry = buildGeneratedRegistry()) {
  const entries = Object.entries(registry).map(
    ([path, entry]) => `  ${JSON.stringify(path)}: ${JSON.stringify(entry)},`
  );
  return [
    "// Generated by scripts/emit-registry.mjs from data/labels.json — do not edit.",
    "export const generatedRegistry = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}
