// Build the report formatting vector: the display string the frontend would
// produce for a bundle value, so the Typst helper can be diffed against it.
// Pure: the emitter and the drift guard share this.

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { fromBase } from "../frontend/src/engine/units.js";
import { formatValue } from "../frontend/src/utils/format.js";

import { readArtifact } from "./report-bundle-glossary.mjs";

const TIGHT_SYMBOLS = new Set(["%"]);
const DASH = "—";

export function readBundle() {
  return JSON.parse(
    readFileSync(
      fileURLToPath(new URL("../tests/conformance/fixtures/report-bundle.json", import.meta.url)),
      "utf8"
    )
  );
}

function unitKind(artifact, dimension) {
  return artifact.dimensions?.[dimension]?.kind ?? "identity";
}

// Mirrors views/producer/scalar.js: convert base -> display unit, then
// `toFixed(decimals)`; a null precision falls back to formatValue, and the
// symbol comes from the bundle's own catalog entry.
export function displayString(artifact, { value, dimension, unit, symbol, decimals }) {
  if (value === null || value === undefined) return DASH;
  if (typeof value !== "number") return String(value);
  const shown = fromBase(artifact, dimension, unit, value);
  const text =
    decimals === null || decimals === undefined ? formatValue(shown) : shown.toFixed(decimals);
  if (!symbol) return text;
  return TIGHT_SYMBOLS.has(symbol) ? `${text}${symbol}` : `${text} ${symbol}`;
}

// Linear and affine units are evaluable from the bundle's own dimension block;
// nonlinear units need an engine function and are out of scope until a section
// asks for one (plans/report-renderer.md §6.5).
function isEvaluable(artifact, dimension) {
  const kind = unitKind(artifact, dimension);
  return kind === "linear" || kind === "affine" || kind === "identity";
}

// Cases chosen to exercise every conversion kind and precision path without
// depending on the fixture's state. Values avoid exact .5 ties, where JS
// toFixed and Typst's calc.round may disagree for reasons unrelated to the rule.
const SYNTHETIC_CASES = [
  { value: 68.3, dimension: "temperature", unit: "degF", symbol: "°F", decimals: 1 },
  { value: 19.5, dimension: "volume", unit: "gal", symbol: "gal", decimals: 1 },
  { value: 0.0035, dimension: "mass", unit: "g", symbol: "g", decimals: 1 },
  { value: 90, dimension: "time", unit: "hr", symbol: "hr", decimals: 1 },
  { value: 90, dimension: "time", unit: "min", symbol: "min", decimals: 0 },
  { value: 0.7531, dimension: "percentage", unit: "pct", symbol: "%", decimals: 1 },
  { value: 5, dimension: "grain_color", unit: "EBC", symbol: "EBC", decimals: 1 },
  { value: 1.23456, dimension: "dimensionless", unit: "1", symbol: null, decimals: null },
  { value: 8, dimension: "dimensionless", unit: "1", symbol: null, decimals: null },
  { value: 0, dimension: "volume", unit: "L", symbol: "L", decimals: 2 },
];

export function buildFormatVector(artifact, bundle) {
  const paths = [];
  for (const path of Object.keys(bundle.state.valuation).sort()) {
    const entry = bundle.catalog.nodes?.[path];
    const value = bundle.state.valuation[path];
    if (!entry || typeof value !== "number") continue;
    if (!entry.dimension || !isEvaluable(artifact, entry.dimension)) continue;
    paths.push({ path, display: displayString(artifact, { value, ...entry }) });
  }

  const cases = SYNTHETIC_CASES.filter((c) => isEvaluable(artifact, c.dimension)).map((c) => ({
    ...c,
    display: displayString(artifact, c),
  }));

  return {
    note: "Generated by scripts/emit-report-format-vector.mjs — do not edit by hand.",
    bundle: "tests/conformance/fixtures/report-bundle.json",
    paths,
    cases,
  };
}

export { readArtifact };
